    policy_owner VARCHAR(100),
    owner VARCHAR(100),
    product VARCHAR(200),
    policy_register_status VARCHAR(100),
    effective_date DATE,
    received_commission DECIMAL(15,2),
    written_commission DECIMAL(15,2),
    premium_amount DECIMAL(15,2),
    advisor_name VARCHAR(100),
    policy_number VARCHAR(100),
    fund_history TEXT,
    status VARCHAR(50) DEFAULT 'Active',
    
    -- Valuation Details
    valuation_entity VARCHAR(100),
    valuation_date DATE,
    valuation_amount DECIMAL(15,2),
    cash_account_amount DECIMAL(15,2),
    provider_name VARCHAR(100),
    provider_client_number VARCHAR(100),
    income_amount DECIMAL(15,2),
    income_to_date DECIMAL(15,2),
    workflow_status VARCHAR(100),
    email_link_sent BOOLEAN DEFAULT FALSE,
    assigned_to VARCHAR(100),
    
    created_on TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
