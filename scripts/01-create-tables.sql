-- Create indexes for better performance
CREATE INDEX IF NOT EXISTS idx_leads_owner ON leads(owner);
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads(current_status);
CREATE INDEX IF NOT EXISTS idx_leads_created ON leads(created_on);

CREATE INDEX IF NOT EXISTS idx_contacts_owner ON contacts(owner);
CREATE INDEX IF NOT EXISTS idx_contacts_status ON contacts(status);
CREATE INDEX IF NOT EXISTS idx_contacts_originating_lead ON contacts(originating_lead);

CREATE INDEX IF NOT EXISTS idx_opportunities_contact_id ON opportunities(contact_id);
CREATE INDEX IF NOT EXISTS idx_opportunities_stage ON opportunities(stage);
CREATE INDEX IF NOT EXISTS idx_opportunities_owner ON opportunities(owner);

CREATE INDEX IF NOT EXISTS idx_factfinds_contact_id ON factfinds(contact_id);
CREATE INDEX IF NOT EXISTS idx_policies_opportunity_id ON policies_valuations(opportunity_id);
